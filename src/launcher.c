/*
 * Clean Desktop — the app's main executable.
 *
 * This has to be a compiled binary rather than a shell script. macOS
 * attributes file-access permission (TCC) to the binary a process is actually
 * running, so while Contents/MacOS/"Clean Desktop" was a #!/bin/bash script,
 * every run identified itself to tccd as com.apple.bash:
 *
 *     AUTHREQ_ATTRIBUTION: accessing={identifier=com.apple.bash,
 *                                     binary_path=/bin/bash}
 *     service="kTCCServiceSystemPolicyDesktopFolder"
 *     Platform binary prompting is 'Deny' because: is Platform Binary
 *
 * Apple platform binaries are never prompted for, so the app was refused
 * access to ~/Desktop without ever asking — and could not be fixed by hand
 * either, because a System Settings grant keys on the app bundle and the
 * running process never matched it. A compiled launcher carries the bundle's
 * own code identity, so the prompt appears once and the grant sticks. The
 * cleaner script spawned below inherits that identity as its responsible
 * process.
 *
 * The path to that script is NOT baked in at build time: it is read at startup
 * from Contents/Resources/runtime-path, which install.sh writes before signing.
 * That keeps this binary byte-identical on every machine, so one prebuilt
 * universal build can be attached to a GitHub release and downloaded instead of
 * requiring the Xcode Command Line Tools to install. Per machine the path file
 * is stable, so re-running install.sh reproduces the same bundle hash and an
 * existing permission grant keeps working.
 *
 * Keep this deterministic — no __DATE__, no build stamps.
 */

#include <errno.h>
#include <fcntl.h>
#include <limits.h>
#include <mach-o/dyld.h>
#include <spawn.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>
#include <sys/wait.h>
#include <unistd.h>

extern char **environ;

/* install.sh greps the executable for this before replacing an existing app,
   so it never clobbers a "Clean Desktop.app" it didn't generate. Externally
   visible and marked used so it survives optimisation. */
__attribute__((used))
const char DesktopCleanerMarker[] =
    "Clean Desktop - generated by Desktop Cleaner install.sh";

/* Written by install.sh, relative to Contents/. */
static const char kRuntimePathFile[] = "Resources/runtime-path";

/* Best-effort macOS notification; never fails the run. */
static void notify(const char *message) {
  char script[512];
  if (snprintf(script, sizeof script,
               "display notification \"%s\" with title \"Desktop Cleaner\"",
               message) >= (int)sizeof script) {
    return;
  }

  char *argv[] = {"/usr/bin/osascript", "-e", script, NULL};
  posix_spawn_file_actions_t actions;
  if (posix_spawn_file_actions_init(&actions) != 0) {
    return;
  }
  posix_spawn_file_actions_addopen(&actions, STDOUT_FILENO, "/dev/null",
                                   O_WRONLY, 0);
  posix_spawn_file_actions_addopen(&actions, STDERR_FILENO, "/dev/null",
                                   O_WRONLY, 0);

  pid_t pid;
  if (posix_spawn(&pid, argv[0], &actions, NULL, argv, environ) == 0) {
    waitpid(pid, NULL, 0);
  }
  posix_spawn_file_actions_destroy(&actions);
}

/* mkdir -p. Returns 0 if the directory exists afterwards. A TCC block shows up
   here as EPERM, which is a failure like any other. */
static int make_dirs(const char *path) {
  char buf[PATH_MAX];
  if (strlen(path) >= sizeof buf) {
    return -1;
  }
  strcpy(buf, path);

  for (char *p = buf + 1; *p != '\0'; p++) {
    if (*p != '/') {
      continue;
    }
    *p = '\0';
    if (mkdir(buf, 0755) != 0 && errno != EEXIST) {
      return -1;
    }
    *p = '/';
  }
  if (mkdir(buf, 0755) != 0 && errno != EEXIST) {
    return -1;
  }
  return 0;
}

/* The cleaner prints a 🧹 banner the moment it starts. Its absence after a
   non-zero exit means it never got going, rather than having run and failed. */
static int log_has_banner(const char *path) {
  static const char kBroom[] = "\xF0\x9F\xA7\xB9"; /* U+1F9F9 */

  FILE *f = fopen(path, "rb");
  if (f == NULL) {
    return 0;
  }
  char buf[4096];
  size_t n = fread(buf, 1, sizeof buf - 1, f);
  fclose(f);
  buf[n] = '\0';

  return strstr(buf, kBroom) != NULL;
}

/* Resolve Contents/Resources/runtime-path next to this executable, which lives
   at <bundle>/Contents/MacOS/<name>. Returns 0 on success. */
static int runtime_path_file(char *out, size_t out_size) {
  char raw[PATH_MAX];
  uint32_t size = sizeof raw;
  if (_NSGetExecutablePath(raw, &size) != 0) {
    return -1;
  }

  char exec_path[PATH_MAX];
  if (realpath(raw, exec_path) == NULL) {
    return -1;
  }

  /* Strip the executable name, then the MacOS/ component, landing in Contents/. */
  for (int i = 0; i < 2; i++) {
    char *slash = strrchr(exec_path, '/');
    if (slash == NULL || slash == exec_path) {
      return -1;
    }
    *slash = '\0';
  }

  if ((size_t)snprintf(out, out_size, "%s/%s", exec_path, kRuntimePathFile) >=
      out_size) {
    return -1;
  }
  return 0;
}

/* Read the cleaner's path, trimming the trailing newline install.sh writes. */
static int read_runtime_path(char *out, size_t out_size) {
  char file[PATH_MAX];
  if (runtime_path_file(file, sizeof file) != 0) {
    return -1;
  }

  FILE *f = fopen(file, "rb");
  if (f == NULL) {
    return -1;
  }
  size_t n = fread(out, 1, out_size - 1, f);
  int truncated = (n == out_size - 1) && (fgetc(f) != EOF);
  fclose(f);
  if (n == 0 || truncated) {
    return -1;
  }
  out[n] = '\0';

  while (n > 0 && (out[n - 1] == '\n' || out[n - 1] == '\r')) {
    out[--n] = '\0';
  }
  return (n > 0) ? 0 : -1;
}

int main(void) {
  const char *home = getenv("HOME");
  if (home == NULL || *home == '\0') {
    notify("Could not work out your home folder. Nothing moved.");
    return 1;
  }

  char script[PATH_MAX];
  if (read_runtime_path(script, sizeof script) != 0) {
    notify("Clean Desktop is missing its runtime path - re-run install.sh. "
           "Nothing moved.");
    return 1;
  }

  char dest_buf[PATH_MAX];
  const char *dest = getenv("DESKTOP_CLEANER_DEST");
  if (dest == NULL || *dest == '\0') {
    if (snprintf(dest_buf, sizeof dest_buf, "%s/Documents/Filed", home) >=
        (int)sizeof dest_buf) {
      notify("That home folder path is too long. Nothing moved.");
      return 1;
    }
    dest = dest_buf;
  }

  /* Log beside the moved files, or in the temp dir if that isn't reachable —
     a blocked run should still leave something to read. */
  const char *log_dir = dest;
  if (make_dirs(dest) != 0) {
    const char *tmp = getenv("TMPDIR");
    log_dir = (tmp != NULL && *tmp != '\0') ? tmp : "/tmp";
  }
  char log_path[PATH_MAX];
  if (snprintf(log_path, sizeof log_path, "%s/.last-run.txt", log_dir) >=
      (int)sizeof log_path) {
    notify("That log path is too long. Nothing moved.");
    return 1;
  }

  if (access(script, X_OK) != 0) {
    notify("Can't run the Desktop Cleaner script - moved or access blocked? "
           "Re-run install.sh. Nothing moved.");
    return 1;
  }

  /* Spawn rather than exec, so a refused start can still be reported instead
     of dying silently. Output → the run log; the cleaner posts its own
     notifications once it is actually running. */
  posix_spawn_file_actions_t actions;
  if (posix_spawn_file_actions_init(&actions) != 0) {
    notify("Could not start Clean Desktop. Nothing moved.");
    return 1;
  }
  posix_spawn_file_actions_addopen(&actions, STDOUT_FILENO, log_path,
                                   O_WRONLY | O_CREAT | O_TRUNC, 0644);
  posix_spawn_file_actions_adddup2(&actions, STDOUT_FILENO, STDERR_FILENO);

  char *argv[] = {script, NULL};
  pid_t pid;
  int rc = posix_spawn(&pid, script, &actions, NULL, argv, environ);
  posix_spawn_file_actions_destroy(&actions);
  if (rc != 0) {
    notify("Clean Desktop couldn't start - re-run install.sh. Nothing moved.");
    return 1;
  }

  int status = 0;
  if (waitpid(pid, &status, 0) < 0) {
    return 1;
  }
  int code = WIFEXITED(status) ? WEXITSTATUS(status) : 1;

  if (code != 0 && !log_has_banner(log_path)) {
    notify("Clean Desktop couldn't start - check the run log, then re-run "
           "install.sh. Nothing moved.");
  }
  return code;
}
